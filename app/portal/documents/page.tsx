import Link from "next/link"
import { DoNextFaq } from "@/components/cms/do-next-faq"
import { EmptyState, PageHeader, StatusBadge } from "@/components/product"
import { agreementsForParty } from "@/lib/role-cms-store"
import { getSessionUser } from "@/lib/session"

export const metadata = { title: "Documents" }

export default async function PortalDocumentsPage() {
  const user = await getSessionUser()
  if (!user) return null
  const docs = agreementsForParty(user.company ?? user.name)
  return (
    <div>
      <PageHeader kicker="Lease docs" title="Documents" lede="Demo rental agreements generated by your landlord. Download or complete e-sign stubs." />
      {docs.length === 0 ? (
        <EmptyState title="No agreements yet" body="When your landlord generates a lease packet, it appears here." action={{ href: "/profile", label: "Open profile" }} />
      ) : (
        <ul className="grid gap-3">
          {docs.map((doc) => (
            <li key={doc.id} className="flex flex-wrap items-center justify-between gap-3 border border-ink/10 bg-card p-4">
              <div>
                <p className="font-semibold">{doc.propertyLabel} · Unit {doc.unitCode}</p>
                <p className="text-sm text-ink-soft">{doc.landlordName}</p>
              </div>
              <StatusBadge status={doc.status === "ready" ? "pending" : doc.status.includes("signed") || doc.status.includes("esign") ? "approved" : "pending"} />
              <Link href={`/agreements/${doc.id}`} className="text-sm font-semibold text-terra hover:underline">Open</Link>
            </li>
          ))}
        </ul>
      )}
      <DoNextFaq
        steps={[
          { title: "Open the packet", body: "Review the English India C&I template." },
          { title: "Download or e-sign", body: "Use demo e-sign or Aadhaar eSign stub — not live DigiLocker." },
          { title: "Keep a copy", body: "Re-download anytime from this list." },
        ]}
        faqs={[
          { q: "Is this a live government eSign?", a: "No. Labels say Demo. No UIDAI or DigiLocker calls." },
        ]}
      />
    </div>
  )
}
